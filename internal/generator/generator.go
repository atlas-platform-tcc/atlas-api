// Package generator renders the files of a service repository from the template
// files and a validated intent. It is pure: no I/O, fully testable.
package generator

import (
	"fmt"
	"strings"

	"github.com/atlas-platform-tcc/atlas-api/internal/domain"
)

// Files maps a repo-relative path to its content.
type Files map[string][]byte

// Paths regenerated from the intent (everything else is copied verbatim, so the
// platform guardrails baked into the template — Dockerfile, probes via chart,
// CI pipeline — are preserved by construction).
const (
	pathGoMod  = "go.mod"
	pathValues = "deploy/values.yaml"
)

// Render produces the generated repository files from the template and the intent.
func Render(template Files, svc domain.Service) Files {
	out := make(Files, len(template)+2)
	for path, content := range template {
		out[path] = content
	}
	out[pathGoMod] = []byte(renderGoMod(svc))
	out[pathValues] = []byte(renderValues(svc))
	return out
}

func renderGoMod(svc domain.Service) string {
	return fmt.Sprintf("module %s\n\ngo 1.26\n", svc.Name)
}

func renderValues(svc domain.Service) string {
	env := envFor(svc)

	var b strings.Builder
	b.WriteString("# Runtime configuration for this service — the only file you edit to tune the deployment.\n")
	fmt.Fprintf(&b, "replicaCount: %d\n", svc.Replicas)
	if len(env) == 0 {
		b.WriteString("env: []\n")
		return b.String()
	}
	b.WriteString("env:\n")
	for _, e := range env {
		fmt.Fprintf(&b, "  - name: %s\n    value: %q\n", e.Name, e.Value)
	}
	return b.String()
}

// AppConfig holds the repository coordinates the generated Argo CD Application
// points to: the base chart (in atlas-templates) and the per-service values
// (in atlas-gitops), combined through Argo CD's multi-source $values reference.
type AppConfig struct {
	Org           string // GitHub org, e.g. "atlas-platform-tcc"
	TemplatesRepo string // chart repository, e.g. "atlas-templates"
	TemplatesRef  string // chart revision, e.g. "main"
	ChartPath     string // chart path within TemplatesRepo, e.g. "charts/base"
	GitopsRepo    string // values repository, e.g. "atlas-gitops"
	GitopsRef     string // values revision, e.g. "main"
}

func repoURL(org, repo string) string {
	return fmt.Sprintf("https://github.com/%s/%s.git", org, repo)
}

// Image is the container image pinned in the GitOps values: the base image CI
// builds from the service's initial commit (repository + tag = commit SHA).
type Image struct {
	Repository string // e.g. ghcr.io/atlas-platform-tcc/billing
	Tag        string // e.g. the initial commit SHA
}

// RenderApplication produces the Argo CD Application manifest for the service,
// combining the shared base chart (atlas-templates) with the per-service values
// (atlas-gitops) through Argo CD's multi-source $values reference. The namespace
// is owned by atlas-infra (Terraform), so the Application does NOT create it:
// if the namespace is not there yet, Argo CD retries until atlas-infra is merged
// (self-heal), keeping the infra/GitOps merge order independent.
func RenderApplication(svc domain.Service, cfg AppConfig) string {
	return fmt.Sprintf(`# Generated by Atlas. Argo CD Application for service %[1]s.
# Combines the shared base chart (atlas-templates) with the per-service values
# (atlas-gitops, via the $values multi-source reference). The values pin the base
# image built from the service's initial commit, so merging this brings up the base
# version once the image is built and the namespace (atlas-infra) exists.
apiVersion: argoproj.io/v1alpha1
kind: Application
metadata:
  name: %[1]s
  namespace: argocd
  labels:
    app.kubernetes.io/part-of: atlas
spec:
  project: default
  sources:
    - repoURL: %[2]s
      targetRevision: %[3]s
      path: %[4]s
      helm:
        valueFiles:
          - $values/apps/%[1]s/values.yaml
    - repoURL: %[5]s
      targetRevision: %[6]s
      ref: values
  destination:
    server: https://kubernetes.default.svc
    namespace: %[1]s
  syncPolicy:
    automated:
      prune: true
      selfHeal: true
`,
		svc.Name,
		repoURL(cfg.Org, cfg.TemplatesRepo), cfg.TemplatesRef, cfg.ChartPath,
		repoURL(cfg.Org, cfg.GitopsRepo), cfg.GitopsRef,
	)
}

// RenderGitopsValues produces the per-service values file stored in atlas-gitops
// and consumed by the Application through $values. It pins the base image (built
// from the service's initial commit) and the requested replica count, so merging
// the GitOps Pull Request brings up the base version. Day-2 Deploys overwrite
// image.tag with a newer commit SHA (and propagate deploy/values.yaml).
func RenderGitopsValues(svc domain.Service, img Image) string {
	env := envFor(svc)

	var b strings.Builder
	b.WriteString("# Desired state for " + svc.Name + " — consumed by its Argo CD Application ($values).\n")
	b.WriteString("# Base deploy: pins the image built from the service's initial commit and runs the\n")
	b.WriteString("# requested replicas. Day-2 Deploys update image.tag to a newer commit SHA.\n")
	fmt.Fprintf(&b, "replicaCount: %d\n", svc.Replicas)
	b.WriteString("image:\n")
	fmt.Fprintf(&b, "  repository: %s\n", img.Repository)
	fmt.Fprintf(&b, "  tag: %q\n", img.Tag)
	if len(env) == 0 {
		b.WriteString("env: []\n")
		return b.String()
	}
	b.WriteString("env:\n")
	for _, e := range env {
		fmt.Fprintf(&b, "  - name: %s\n    value: %q\n", e.Name, e.Value)
	}
	return b.String()
}

// RenderServiceTF produces the Terraform file (a module call) that declares the
// service's infrastructure in the atlas-infra repository.
func RenderServiceTF(svc domain.Service) string {
	var b strings.Builder
	b.WriteString("# Generated by Atlas. Infrastructure for service " + svc.Name + ".\n")
	fmt.Fprintf(&b, "module %q {\n", svc.Name)
	b.WriteString("  source           = \"../modules/service\"\n")
	fmt.Fprintf(&b, "  name             = %q\n", svc.Name)
	fmt.Fprintf(&b, "  database_enabled = %t\n", svc.Database.Enabled)
	if svc.Database.Enabled {
		fmt.Fprintf(&b, "  database_type    = %q\n", svc.Database.Type)
	}
	// Pass the GHCR pull credentials (root vars) so the module creates the
	// ghcr-pull image pull secret in the service namespace. No secret in git.
	b.WriteString("  ghcr_username    = var.ghcr_username\n")
	b.WriteString("  ghcr_token       = var.ghcr_token\n")
	b.WriteString("}\n")
	return b.String()
}

// envFor returns the intent's env vars, adding DB_TYPE when a database is enabled
// and the developer did not already provide it.
func envFor(svc domain.Service) []domain.EnvVar {
	env := append([]domain.EnvVar(nil), svc.Env...)
	if svc.Database.Enabled {
		has := false
		for _, e := range env {
			if e.Name == "DB_TYPE" {
				has = true
				break
			}
		}
		if !has {
			env = append(env, domain.EnvVar{Name: "DB_TYPE", Value: svc.Database.Type})
		}
	}
	return env
}
