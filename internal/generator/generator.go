// Package generator renders the files of a service repository from the template
// files and a validated intent. It is pure: no I/O, fully testable.
package generator

import (
	"fmt"
	"strings"

	"github.com/atlas-platform-tcc/atlas-api/internal/domain"
)

// Files maps a repo-relative path to its content.
type Files map[string][]byte

// Paths regenerated from the intent (everything else is copied verbatim, so the
// platform guardrails baked into the template — Dockerfile, probes via chart,
// CI pipeline — are preserved by construction).
const (
	pathGoMod          = "go.mod"
	pathValues         = "deploy/values.yaml"
	pathCompose        = "docker-compose.yml"
	pathDotEnvExample  = ".env.example"
	localPostgresImage = "postgres:16-alpine" // homologated for local onboarding only (never deployed)
)

// Render produces the generated repository files from the template and the intent.
func Render(template Files, svc domain.Service) Files {
	out := make(Files, len(template)+3)
	for path, content := range template {
		out[path] = content
	}
	out[pathGoMod] = []byte(renderGoMod(svc))
	out[pathValues] = []byte(renderValues(svc))
	// Local dev environment shaped by the intent (ADR atlas-templates/0008).
	out[pathCompose] = []byte(renderDockerCompose(svc))
	if svc.Database.Enabled {
		// Local-only credentials; the cluster secret is created by atlas-infra and never
		// committed (ADR atlas-templates/0007).
		out[pathDotEnvExample] = []byte(renderDotEnvExample(svc))
	}
	return out
}

func renderGoMod(svc domain.Service) string {
	return fmt.Sprintf("module %s\n\ngo 1.26\n", svc.Name)
}

func renderValues(svc domain.Service) string {
	env := envFor(svc)

	var b strings.Builder
	b.WriteString("# Runtime configuration for this service — the only file you edit to tune the deployment.\n")
	fmt.Fprintf(&b, "replicaCount: %d\n", svc.Replicas)
	if len(env) == 0 {
		b.WriteString("env: []\n")
		return b.String()
	}
	b.WriteString("env:\n")
	for _, e := range env {
		fmt.Fprintf(&b, "  - name: %s\n    value: %q\n", e.Name, e.Value)
	}
	return b.String()
}

// renderDockerCompose produces the local development environment (ADR atlas-templates/0008):
// the service built from its own Dockerfile plus, when the intent asks for a database, a
// PostgreSQL container wired with the same variables the base chart injects in Kubernetes.
// A new developer gets a working environment from `docker compose up` alone.
func renderDockerCompose(svc domain.Service) string {
	var b strings.Builder
	b.WriteString("# Local development environment — generated by Atlas (ADR atlas-templates/0008).\n")
	b.WriteString("# `docker compose up --build` runs the service as it runs in the cluster, with the same\n")
	b.WriteString("# runtime variables. This is NOT production: delivery still flows through Git + Argo CD.\n")
	b.WriteString("services:\n")
	b.WriteString("  app:\n")
	b.WriteString("    build: .\n")
	b.WriteString("    ports:\n")
	b.WriteString("      - \"8080:8080\"\n")
	b.WriteString("    environment:\n")
	b.WriteString("      PORT: \"8080\"\n")

	if svc.Database.Enabled {
		// Same wiring as the base chart (ADR atlas-templates/0007), pointed at the
		// compose Postgres instead of the in-cluster Service.
		b.WriteString("      # Connection mirrored from the cluster: in Kubernetes it comes from the Secret\n")
		b.WriteString("      # via envFrom; here it points to the compose Postgres (ADR atlas-templates/0007).\n")
		b.WriteString("      DB_HOST: postgres\n")
		b.WriteString("      DB_PORT: \"5432\"\n")
		writeComposePostgresEnv(&b, svc, "      ")
	}
	for _, e := range envFor(svc) {
		fmt.Fprintf(&b, "      %s: %q\n", e.Name, e.Value)
	}

	if !svc.Database.Enabled {
		return b.String()
	}

	// Starting before Postgres accepts connections would fail /dbz on the first `up`.
	b.WriteString("    depends_on:\n")
	b.WriteString("      postgres:\n")
	b.WriteString("        condition: service_healthy\n")
	fmt.Fprintf(&b, "  postgres:\n    image: %s\n", localPostgresImage)
	b.WriteString("    environment:\n")
	writeComposePostgresEnv(&b, svc, "      ")
	b.WriteString("    ports:\n")
	b.WriteString("      - \"5432:5432\"\n")
	b.WriteString("    healthcheck:\n")
	fmt.Fprintf(&b, "      test: [\"CMD-SHELL\", \"pg_isready -U ${POSTGRES_USER:-postgres} -d ${POSTGRES_DB:-%s}\"]\n", svc.Name)
	b.WriteString("      interval: 5s\n      timeout: 3s\n      retries: 10\n")
	b.WriteString("    volumes:\n      - pgdata:/var/lib/postgresql/data\n")
	b.WriteString("volumes:\n  pgdata:\n")
	return b.String()
}

// writeComposePostgresEnv writes the POSTGRES_* variables shared by the app and the
// Postgres container, overridable via a local .env so `up` stays zero-config.
func writeComposePostgresEnv(b *strings.Builder, svc domain.Service, indent string) {
	fmt.Fprintf(b, "%sPOSTGRES_DB: ${POSTGRES_DB:-%s}\n", indent, svc.Name)
	fmt.Fprintf(b, "%sPOSTGRES_USER: ${POSTGRES_USER:-postgres}\n", indent)
	fmt.Fprintf(b, "%sPOSTGRES_PASSWORD: ${POSTGRES_PASSWORD:-postgres}\n", indent)
}

// renderDotEnvExample documents the overridable local database credentials. Only the
// example is committed: the real .env and the cluster Secret never reach Git
// (ADR atlas-templates/0007).
func renderDotEnvExample(svc domain.Service) string {
	var b strings.Builder
	b.WriteString("# Local development environment variables (docker compose).\n")
	b.WriteString("# Copy to .env and adjust if you want. These values are LOCAL ONLY: the real cluster\n")
	b.WriteString("# secret is created by atlas-infra and never committed to Git (ADR atlas-templates/0007).\n")
	fmt.Fprintf(&b, "POSTGRES_DB=%s\n", svc.Name)
	b.WriteString("POSTGRES_USER=postgres\n")
	b.WriteString("POSTGRES_PASSWORD=postgres\n")
	return b.String()
}

// AppConfig holds the repository coordinates the generated Argo CD Application
// points to: the base chart (in atlas-templates) and the per-service values
// (in atlas-gitops), combined through Argo CD's multi-source $values reference.
type AppConfig struct {
	Org           string // GitHub org, e.g. "atlas-platform-tcc"
	TemplatesRepo string // chart repository, e.g. "atlas-templates"
	TemplatesRef  string // chart revision, e.g. "main"
	ChartPath     string // chart path within TemplatesRepo, e.g. "charts/base"
	GitopsRepo    string // values repository, e.g. "atlas-gitops"
	GitopsRef     string // values revision, e.g. "main"
	IngressDomain string // wildcard domain for service hosts, e.g. "127.0.0.1.nip.io"
}

// ServiceHost is the Ingress host pinned for a service (ADR atlas-templates/0006):
// "<name>.<domain>", e.g. payments.127.0.0.1.nip.io.
func ServiceHost(name, domain string) string {
	return name + "." + domain
}

func repoURL(org, repo string) string {
	return fmt.Sprintf("https://github.com/%s/%s.git", org, repo)
}

// Image is the container image pinned in the GitOps values: the base image CI
// builds from the service's initial commit (repository + tag = commit SHA).
type Image struct {
	Repository string // e.g. ghcr.io/atlas-platform-tcc/billing
	Tag        string // e.g. the initial commit SHA
}

// RenderApplication produces the Argo CD Application manifest for the service,
// combining the shared base chart (atlas-templates) with the per-service values
// (atlas-gitops) through Argo CD's multi-source $values reference. The namespace
// is owned by atlas-infra (Terraform), so the Application does NOT create it:
// if the namespace is not there yet, Argo CD retries until atlas-infra is merged
// (self-heal), keeping the infra/GitOps merge order independent.
//
// The cascade-deletion finalizer makes pruning the Application (on deprovisioning,
// ADR atlas-api/0011) delete its workloads instead of orphaning them.
func RenderApplication(svc domain.Service, cfg AppConfig) string {
	return fmt.Sprintf(`# Generated by Atlas. Argo CD Application for service %[1]s.
# Combines the shared base chart (atlas-templates) with the per-service values
# (atlas-gitops, via the $values multi-source reference). The values pin the base
# image built from the service's initial commit, so merging this brings up the base
# version once the image is built and the namespace (atlas-infra) exists.
apiVersion: argoproj.io/v1alpha1
kind: Application
metadata:
  name: %[1]s
  namespace: argocd
  labels:
    app.kubernetes.io/part-of: atlas
  finalizers:
    - resources-finalizer.argocd.argoproj.io
spec:
  project: default
  sources:
    - repoURL: %[2]s
      targetRevision: %[3]s
      path: %[4]s
      helm:
        valueFiles:
          - $values/apps/%[1]s/values.yaml
    - repoURL: %[5]s
      targetRevision: %[6]s
      ref: values
  destination:
    server: https://kubernetes.default.svc
    namespace: %[1]s
  syncPolicy:
    automated:
      prune: true
      selfHeal: true
`,
		svc.Name,
		repoURL(cfg.Org, cfg.TemplatesRepo), cfg.TemplatesRef, cfg.ChartPath,
		repoURL(cfg.Org, cfg.GitopsRepo), cfg.GitopsRef,
	)
}

// RenderGitopsValues produces the per-service values file stored in atlas-gitops
// and consumed by the Application through $values. It pins the base image (built
// from the service's initial commit) and the requested replica count, so merging
// the GitOps Pull Request brings up the base version. Day-2 Deploys overwrite
// image.tag with a newer commit SHA (and propagate deploy/values.yaml).
func RenderGitopsValues(svc domain.Service, img Image, ingressDomain string) string {
	env := envFor(svc)

	var b strings.Builder
	b.WriteString("# Desired state for " + svc.Name + " — consumed by its Argo CD Application ($values).\n")
	b.WriteString("# Base deploy: pins the image built from the service's initial commit and runs the\n")
	b.WriteString("# requested replicas. Day-2 Deploys update image.tag to a newer commit SHA.\n")
	fmt.Fprintf(&b, "replicaCount: %d\n", svc.Replicas)
	b.WriteString("image:\n")
	fmt.Fprintf(&b, "  repository: %s\n", img.Repository)
	fmt.Fprintf(&b, "  tag: %q\n", img.Tag)

	// Pin the host so the service is reachable at http://<name>.<domain> once
	// ingress-nginx is up (ADR atlas-templates/0006).
	b.WriteString("ingress:\n  enabled: true\n")
	fmt.Fprintf(&b, "  host: %s\n", ServiceHost(svc.Name, ingressDomain))

	// Enables the chart's connection wiring (envFrom the Secret created by atlas-infra).
	if svc.Database.Enabled {
		b.WriteString("database:\n  enabled: true\n")
	}

	if len(env) == 0 {
		b.WriteString("env: []\n")
		return b.String()
	}
	b.WriteString("env:\n")
	for _, e := range env {
		fmt.Fprintf(&b, "  - name: %s\n    value: %q\n", e.Name, e.Value)
	}
	return b.String()
}

// RenderServiceTF produces the Terraform file (a module call) that declares the
// service's infrastructure in the atlas-infra repository.
func RenderServiceTF(svc domain.Service) string {
	var b strings.Builder
	b.WriteString("# Generated by Atlas. Infrastructure for service " + svc.Name + ".\n")
	fmt.Fprintf(&b, "module %q {\n", svc.Name)
	b.WriteString("  source           = \"../modules/service\"\n")
	fmt.Fprintf(&b, "  name             = %q\n", svc.Name)
	fmt.Fprintf(&b, "  database_enabled = %t\n", svc.Database.Enabled)
	if svc.Database.Enabled {
		fmt.Fprintf(&b, "  database_type    = %q\n", svc.Database.Type)
	}
	// Pass the GHCR pull credentials (root vars) so the module creates the
	// ghcr-pull image pull secret in the service namespace. No secret in git.
	b.WriteString("  ghcr_username    = var.ghcr_username\n")
	b.WriteString("  ghcr_token       = var.ghcr_token\n")
	b.WriteString("}\n")
	return b.String()
}

// envFor returns the intent's env vars, adding DB_TYPE when a database is enabled
// and the developer did not already provide it.
func envFor(svc domain.Service) []domain.EnvVar {
	env := append([]domain.EnvVar(nil), svc.Env...)
	if svc.Database.Enabled {
		has := false
		for _, e := range env {
			if e.Name == "DB_TYPE" {
				has = true
				break
			}
		}
		if !has {
			env = append(env, domain.EnvVar{Name: "DB_TYPE", Value: svc.Database.Type})
		}
	}
	return env
}
